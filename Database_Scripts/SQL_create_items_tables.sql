CREATE INDEX ix_tb_items_status_id ON tb_items(status_id);
CREATE INDEX ix_tb_items_cell_id ON tb_items(cell_id);
CREATE INDEX ix_tb_items_id_user ON tb_items(id_user);
CREATE INDEX ix_tb_items_location_id ON tb_items(location_id);

CREATE INDEX ix_his_proc_item_item_id ON his_proc_item(item_id);
CREATE INDEX ix_his_proc_item_create_date ON his_proc_item(create_date);

CREATE INDEX ix_href_cell_line_cell_id ON href_cell_line(cell_id);
CREATE INDEX ix_href_cell_line_line_id ON href_cell_line(line_id);

CREATE INDEX ix_href_routing_cell_routing_id ON href_routing_cell(routing_id);
CREATE INDEX ix_href_routing_cell_cell_id ON href_routing_cell(cell_id);

CREATE INDEX ix_href_routing_model_routing_id ON href_routing_model(routing_id);
CREATE INDEX ix_href_routing_model_model_id ON href_routing_model(model_id);

